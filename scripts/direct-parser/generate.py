# Only immediate constituents of each production get accessors. Repetition controls multiplicity.
def members(expr):
    k,*a=nodes[expr]
    if k in (1,2):return Counter({(k,a[0]):1})
    if k in (5,6,7):return Counter({n:min(2,v*(2 if k!=5 else 1)) for n,v in members(a[0]).items()})
    out=Counter()
    for x in a if k in (3,4) else []:
        c=members(x)
        for n,v in c.items():out[n]=min(2,out[n]+v) if k==3 else max(out[n],v)
    return out
