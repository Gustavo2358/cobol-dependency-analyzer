    def peek(self):return self.ts[self.p] if self.p<len(self.ts) else None
    def alt(self):
        out=[self.seq()]
        while self.peek()=='|':self.take();out.append(self.seq())
        return out[0] if len(out)==1 else node(4,*out)
    def seq(self):
        out=[]
        while self.peek() not in (None,')','|'):
            t=self.take()
            if t=='(':
                x=self.alt();assert self.take()==')'
            elif t in ids:x=node(2,ids[t])
            else:x=node(1,vocab[t])
            if self.peek() in ('?','*','+'):
                q=self.take();x=node({'?':5,'*':6,'+':7}[q],x)
            out.append(x)
        return node(0) if not out else out[0] if len(out)==1 else node(3,*out)
