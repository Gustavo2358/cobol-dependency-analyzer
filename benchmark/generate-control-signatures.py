#!/usr/bin/env python3
"""Generate a linear-size COBOL source with 2**flags possible control inputs.

Each unknown INPUT chooses one of two values and invokes the next paragraph.
Every concrete execution reaches BODY once. All local invocations return.
The predicate and data variants have the same two program dependencies.
This command only generates a source; it does not execute the analyzer.
"""
import argparse
from pathlib import Path


def source(flags, mode):
    if flags < 1:
        raise ValueError('flags must be positive')
    if mode not in ('predicates', 'data'):
        raise ValueError('mode must be predicates or data')
    prefix = 'CTRL' if mode == 'predicates' else 'DATA'
    lines = [
        '*> Generated by benchmark/generate-control-signatures.py.',
        f'*> {flags} independent choices; {2**flags} possible BODY inputs.',
        '*> All calls are reachable; each concrete execution reaches BODY once.',
        '*> Expected program names: ONE00000 and ZERO0000.',
        'IDENTIFICATION DIVISION.', f'PROGRAM-ID. {prefix}FLAGS{flags}.',
        'DATA DIVISION.', 'WORKING-STORAGE SECTION.',
    ]
    for bit in range(1, flags + 1):
        lines.extend([f'01 INPUT-{bit:02d} PIC X.',
                      f'01 FLAG-{bit:02d} PIC X(8).'])
    lines.extend(['PROCEDURE DIVISION.', 'MAIN.',
                  '    PERFORM CHOOSE-01.', '    GOBACK.'])
    for bit in range(1, flags + 1):
        following = f'CHOOSE-{bit + 1:02d}' if bit < flags else 'BODY'
        lines.extend([
            f'CHOOSE-{bit:02d}.', f"    IF INPUT-{bit:02d} = 'Y'",
            f"        MOVE 'ONE00000' TO FLAG-{bit:02d}",
            f'        PERFORM {following}', '    ELSE',
            f"        MOVE 'ZERO0000' TO FLAG-{bit:02d}",
            f'        PERFORM {following}', '    END-IF.', '    EXIT.',
        ])
    lines.append('BODY.')
    for bit in range(1, flags + 1):
        if mode == 'predicates':
            lines.extend([
                f"    IF FLAG-{bit:02d} = 'ONE00000'",
                "        CALL 'ONE00000'", '    ELSE',
                "        CALL 'ZERO0000'", '    END-IF.',
            ])
        else:
            lines.append(f'    CALL FLAG-{bit:02d}.')
    lines.append('    EXIT.')
    return ''.join('       ' + line + '\n' for line in lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--flags', type=int, default=10)
    parser.add_argument('--mode', choices=('predicates', 'data'), default='predicates')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    if args.flags < 1:
        parser.error('--flags must be positive')
    text = source(args.flags, args.mode)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding='utf-8')
    print(f'{args.output}: {len(text.splitlines())} lines, '
          f'{2**args.flags} possible inputs, mode={args.mode}')


if __name__ == '__main__':
    main()
